static void set_error(char *out, size_t out_len, int *nstop, const char *message)
{
    size_t n = strlen(message);
    if (n > out_len) n = out_len;
    memset(out, ' ', out_len);
    memcpy(out, message, n);
    *nstop = 1;
}

static int begins(const char *s, size_t n, const char *prefix, size_t prefix_len)
{
    return n >= prefix_len && memcmp(s, prefix, prefix_len) == 0;
}

extern "C" void interpdielec_(const REAL *lambdat, const char *materiau,
                   REAL *epr, REAL *epi, char *infostr, int *nstop,
                   size_t materiau_len, size_t infostr_len)
{
    if (!lambdat || !materiau || !epr || !epi || !infostr || !nstop)
        return;
    *nstop = 0;
    const optical_point *table = NULL;
    const char *matname = NULL;
    int upper_exclusive = 0;
    size_t count = 0;
    REAL npointe, kpointe, coeff;
    size_t il = 0, i;
    const REAL lambda = *lambdat;

    if (begins(materiau, materiau_len, "Glass", 5)) {
        npointe = 1.50;
        kpointe = 0.0;
    } else if (begins(materiau, materiau_len, "vi", 2)) {
        npointe = 1.0;
        kpointe = 0.0;
    } else if (begins(materiau, materiau_len, "Water", 5)) {
        npointe = 1.330413469560070;
        kpointe = 0.0;
    } else {

        if (begins(materiau, materiau_len, "Ag", 2)) {
            table = table_Ag; count = sizeof(table_Ag)/sizeof(table_Ag[0]); matname = "Ag";
        }
        else if (begins(materiau, materiau_len, "Au", 2)) {
            table = table_Au; count = sizeof(table_Au)/sizeof(table_Au[0]); matname = "Au"; upper_exclusive = 1;
        }
        else if (begins(materiau, materiau_len, "Si", 2)) {
            table = table_Si; count = sizeof(table_Si)/sizeof(table_Si[0]); matname = "Si";
        }
        else if (begins(materiau, materiau_len, "Al", 2)) {
            table = table_Al; count = sizeof(table_Al)/sizeof(table_Al[0]); matname = "Al";
        }
        else if (begins(materiau, materiau_len, "Cu", 2)) {
            table = table_Cu; count = sizeof(table_Cu)/sizeof(table_Cu[0]); matname = "Cu";
        }
        else if (begins(materiau, materiau_len, "Ir", 2)) {
            table = table_Ir; count = sizeof(table_Ir)/sizeof(table_Ir[0]); matname = "Ir";
        }
        else if (begins(materiau, materiau_len, "Mo", 2)) {
            table = table_Mo; count = sizeof(table_Mo)/sizeof(table_Mo[0]); matname = "Mo";
        }
        else if (begins(materiau, materiau_len, "Ni", 2)) {
            table = table_Ni; count = sizeof(table_Ni)/sizeof(table_Ni[0]); matname = "Ni";
        }
        else if (begins(materiau, materiau_len, "Os", 2)) {
            table = table_Os; count = sizeof(table_Os)/sizeof(table_Os[0]); matname = "Os";
        }
        else if (begins(materiau, materiau_len, "Pt", 2)) {
            table = table_Pt; count = sizeof(table_Pt)/sizeof(table_Pt[0]); matname = "Pt";
        }
        else if (begins(materiau, materiau_len, "Rh", 2)) {
            table = table_Rh; count = sizeof(table_Rh)/sizeof(table_Rh[0]); matname = "Rh";
        }
        else if (begins(materiau, materiau_len, "W", 1)) {
            table = table_W; count = sizeof(table_W)/sizeof(table_W[0]); matname = "W";
        }
        else {
            set_error(infostr, infostr_len, nstop, "Material not in memory");
            return;
        }
        /* Keep the source routine's endpoint test and ascending-interval scan. */
        if (lambda < table[0].lambda || lambda > table[count-1].lambda) {
            char message[96];
            (void)snprintf(message, sizeof(message), "wavelength out of range for %s", matname);
            set_error(infostr, infostr_len, nstop, message);
            return;
        }
        for (i = 1; i < count; ++i) {
            if (lambda >= table[i-1].lambda &&
                (upper_exclusive ? lambda < table[i].lambda : lambda <= table[i].lambda))
                il = i-1;
        }
        coeff = (lambda-table[il].lambda)/(table[il+1].lambda-table[il].lambda);
        npointe = table[il].n + (table[il+1].n-table[il].n)*coeff;
        kpointe = table[il].k + (table[il+1].k-table[il].k)*coeff;
    }
    if (!initialize_cuda_device()) {
        set_error(infostr, infostr_len, nstop,
                  "CUDA initialization failed for dielectric interpolation");
        return;
    }
    cuda_data::MaterialInterpolationDeviceBuffers buffers{};
    if (!cuda_data::get_device_material_interpolation_buffers(&buffers) || !buffers.result) {
        set_error(infostr, infostr_len, nstop,
                  "CUDA dielectric interpolation buffer unavailable");
        return;
    }
    const cudaError_t launch_status =
        material_interpolation_wrapper(buffers.result, npointe, kpointe);
    if (!cuda_utils::check_cuda(launch_status, "dielectric interpolation",
                                "compute permittivity")) {
        set_error(infostr, infostr_len, nstop, "CUDA dielectric interpolation failed");
        return;
    }
    REAL result[2] = {REAL(0), REAL(0)};
    if (!cuda_utils::check_cuda(
            cuda_data::copy_device_to_host(result, buffers.result, sizeof(result),
                                           cuda_utils::TransferCategory::Material),
            "dielectric interpolation", "download permittivity")) {
        set_error(infostr, infostr_len, nstop,
                  "CUDA dielectric interpolation result copy failed");
        return;
    }
    *epr = result[0];
    *epi = result[1];
    (void)printf(" index real % .16E imag % .16E\n", npointe, kpointe);
    (void)printf(" epsilon real % .16E imag % .16E\n", *epr, *epi);
}

